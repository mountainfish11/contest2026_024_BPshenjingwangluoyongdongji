#!/usr/bin/env python3
"""Generate the firmware CJK bitmap table using WenQuanYi Zen Hei and Pillow."""

import argparse
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--font', default='/usr/share/fonts/truetype/wqy/wqy-zenhei.ttc')
    args = parser.parse_args()
    target = Path(__file__).resolve().parents[1] / 'app/blind_badge_app'
    font = ImageFont.truetype(args.font, 16)
    points = list(range(0x3000, 0x3040)) + list(range(0x4e00, 0xa000))
    points += list(range(0xff01, 0xff61))
    output = [
        '/* Generated by tools/generate_lcd_font.py; do not edit manually.',
        ' * WenQuanYi Zen Hei, 16px. See FONT-LICENSE.txt. */',
        'static const struct blind_badge_cjk_glyph g_cjk_full_glyphs[] =',
        '{',
    ]
    for point in points:
        bitmap = Image.new('L', (16, 16))
        ImageDraw.Draw(bitmap).text((0, -1), chr(point), font=font, fill=255)
        rows = [sum((1 << (15-x)) for x in range(16)
                    if bitmap.getpixel((x, y)) >= 96) for y in range(16)]
        output.append('  {0x%04x, {%s}},' %
                      (point, ', '.join('0x%04x' % row for row in rows)))
    output.append('};')
    (target / 'blind_badge_cjk_font.h').write_text('\n'.join(output) + '\n')
    license_path = Path('/usr/share/doc/fonts-wqy-zenhei/copyright')
    (target / 'FONT-LICENSE.txt').write_text(license_path.read_text())
    print('Generated %d glyphs' % len(points))


if __name__ == '__main__':
    main()
